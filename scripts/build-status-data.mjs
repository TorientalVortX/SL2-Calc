/**
 * Turns the scraped status-effect catalog into the calculator's status dataset.
 *
 *   wiki-data/raw/statuses.json  ->  src/data/content/statuses.json
 *                                ->  optimizer-knowledge/01-core-mechanics/status-effects-catalog.md
 *
 * The wiki writes each status as prose. Only claims the text states plainly are
 * lifted into structured fields: racial infliction immunities, the post-recovery
 * immunity window, protection-ignoring and per-round damage markers, and which
 * status a Hex locks against curing. Everything else stays as description text
 * rather than being turned into numbers the source does not support.
 *
 * The knowledge markdown is generated here so the AI planner's local corpus
 * always matches the dataset the calculator ships; it carries an auto-generated
 * header pointing back at this script.
 *
 *   node scripts/build-status-data.mjs
 *   node scripts/build-status-data.mjs --report
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const IN = path.resolve('wiki-data/raw/statuses.json');
const RACES_IN = path.resolve('src/data/content/races.json');
const OUT = path.resolve('src/data/content/statuses.json');
const KNOWLEDGE_OUT = path.resolve('optimizer-knowledge/01-core-mechanics/status-effects-catalog.md');
const REPORT = process.argv.includes('--report');

const raw = JSON.parse(await readFile(IN, 'utf8'));

/*
 * Immunity subjects are resolved against the calculator's own race list, the
 * same rule build-trait-data.mjs uses: a name the calculator has never heard of
 * must stay visible as prose rather than silently becoming a dead check. The
 * unresolved ones here are monster races (Snakemen, Drowned Woman).
 */
const raceData = JSON.parse(await readFile(RACES_IN, 'utf8'));
const KNOWN_RACES = new Set([...Object.keys(raceData.races), ...Object.keys(raceData.subraces)]);

const kebab = (name) => name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

/** `"Glykin, Dullahan and Snakemen are immune to Poison infliction"` → subjects. */
function parseImmunities(text) {
  const immuneRaces = [];
  const otherImmune = [];
  for (const match of text.matchAll(/([A-Za-z' ,-]+?)\s+(?:is|are)\s+immune\s+to\s+([A-Za-z ]+?)\s+infliction/g)) {
    for (const subject of match[1].split(/,|\band\b/).map(part => part.trim()).filter(Boolean)) {
      (KNOWN_RACES.has(subject) ? immuneRaces : otherImmune).push(subject);
    }
  }
  return { immuneRaces, otherImmune };
}

const statuses = raw.sections.flatMap(section => section.rows.map(row => {
  const combined = `${row.description} ${row.notes}`;
  const { immuneRaces, otherImmune } = parseImmunities(combined);
  const recovery = combined.match(/Grants (\d+) rounds? of immunity after recovery/i);
  const curePrevention = combined.match(/Prevents ([A-Za-z ]+?) from being cured/i);
  return {
    id: kebab(row.name),
    name: row.name,
    category: section.title,
    description: row.description,
    notes: row.notes,
    immuneRaces,
    ...(otherImmune.length ? { otherImmune } : {}),
    ...(recovery ? { recoveryImmunityRounds: Number(recovery[1]) } : {}),
    ...(curePrevention ? { preventsCureOf: curePrevention[1].trim() } : {}),
    protectionIgnoring: /protection-ignoring|ignores protection/i.test(combined),
    perRound: /every round/i.test(combined),
    links: row.links,
  };
}));

const payload = {
  schemaVersion: 1,
  source: raw.source,
  scraped: raw.scraped,
  confidence: 'community',
  statuses,
};
await writeFile(OUT, `${JSON.stringify(payload, null, 2)}\n`, 'utf8');

/* -------------------------------------------------- knowledge base markdown */

const categories = raw.sections.filter(section => section.rows.length);
const withImmunities = statuses.filter(status => status.immuneRaces.length || status.otherImmune?.length);
const knowledge = [
  '# Status effect catalog',
  '',
  `Generated by \`scripts/build-status-data.mjs\` from the scraped wiki catalog. Edit the script or rescrape, not this file. Scraped: ${raw.scraped}. Source: [Status Effects](${raw.source}). Confidence: \`community\`.`,
  '',
  '## What this supports',
  '',
  '- Per-status descriptions and categories for reasoning about status builds and counters.',
  '- Racial infliction immunities the calculator can check (resolved against canonical race names).',
  '- Post-recovery immunity windows, protection-ignoring markers, and Hex cure locks, where the wiki states them.',
  '',
  '## What this does not support',
  '',
  '- Durations, infliction chances per skill, or which skills apply each status: those need per-skill records.',
  '- The generic Status Infliction vs Resistance contest stays `2×SKI+WIL` vs `2×SAN+FAI` (see `calculator-model-and-public-comparison.md`); individual skills may use reduced or unique formulas.',
  '- Do not invent numbers for statuses whose text is qualitative.',
  '',
  '## Racial infliction immunities',
  '',
  ...withImmunities.map(status => `- **${status.name}**: ${[...status.immuneRaces, ...(status.otherImmune ?? [])].join(', ')} cannot be inflicted.`),
  '',
  ...categories.flatMap(section => [
    `## ${section.title}`,
    '',
    ...(section.intro ? [section.intro, ''] : []),
    '| Status | Description | Notes |',
    '| --- | --- | --- |',
    ...section.rows.map(row => `| ${row.name} | ${row.description || '—'} | ${row.notes || '—'} |`),
    '',
  ]),
].join('\n');
await writeFile(KNOWLEDGE_OUT, `${knowledge}\n`, 'utf8');

console.log(`Wrote ${statuses.length} statuses across ${categories.length} categories to src/data/content/statuses.json`);
console.log(`Wrote optimizer-knowledge/01-core-mechanics/status-effects-catalog.md`);
if (REPORT) {
  for (const status of withImmunities) {
    console.log(`  immunity: ${status.name} <- ${[...status.immuneRaces, ...(status.otherImmune ?? [])].join(', ')}`);
  }
  const unresolved = statuses.flatMap(status => status.otherImmune ?? []);
  if (unresolved.length) console.log(`  unresolved immunity subjects (kept as prose): ${[...new Set(unresolved)].join(', ')}`);
}
